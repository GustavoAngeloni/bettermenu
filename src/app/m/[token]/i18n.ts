export const DICTS: Record<Lang, Dict> = { pt, en, es };

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem("bm_lang");
    if (saved === "pt" || saved === "en" || saved === "es") return saved;
  } catch {}
  const nav = typeof navigator !== "undefined" ? navigator.language.slice(0, 2) : "pt";
  return nav === "en" || nav === "es" ? nav : "pt";
}

/** Nome/descrição traduzidos, com fallback em português. */
export function tr(lang: Lang, base: { name: string; description?: string | null; translations?: Partial<Record<"en" | "es", { name?: string; description?: string }>> }) {
  const t = lang === "pt" ? undefined : base.translations?.[lang];
  return { name: t?.name || base.name, description: t?.description || base.description || null };
}
